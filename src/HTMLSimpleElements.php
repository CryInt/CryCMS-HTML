abstract class HTMLSimpleElements extends HTMLHelper
{
    /**
     * @var array<int, string>
     */
    protected static array $simpleElements = [
        'abbr', 'address', 'article', 'aside', 'audio',
        'b', 'bdo', 'body', 'blockquote', 'button',
